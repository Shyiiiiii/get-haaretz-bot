// ממוין מהארוך לקצר — קריטי להתאמה נכונה
const SORTED = [...CITIES].sort((a, b) => b.length - a.length);

/**
 * מחלץ עד שני שמות ערים מטקסט, בהתאמה חמדנית (הארוך קודם).
 * מחזיר מערך שמות מלאים.
 */
function extractCities(text) {
  let t = ' ' + String(text).replace(/["״'׳]/g, '') + ' ';
  const found = [];

  // 1) ערים מלאות (כולל דו-מיליות), עם תמיכה בתחיליות ל/מ/ב/ו
  for (const city of SORTED) {
    const re = new RegExp(`\\s([למבו])?${city.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?=\\s)`);
    const m = t.match(re);
    if (m) {
      found.push({ city, pos: m.index });
      t = t.slice(0, m.index) + ' '.repeat(m[0].length) + t.slice(m.index + m[0].length);
    }
  }

  // 2) קיצורים על מה שנשאר
  for (const [ab, full] of Object.entries(ABBR)) {
    const re = new RegExp(`\\s([למבו])?${ab}(?=\\s)`);
    const m = t.match(re);
    if (m) {
      found.push({ city: full, pos: m.index });
      t = t.slice(0, m.index) + ' '.repeat(m[0].length) + t.slice(m.index + m[0].length);
    }
  }

  // דה-דופליקציה תוך שמירת סדר ההופעה
  const seen = new Set();
  return found.sort((a, b) => a.pos - b.pos).map((f) => f.city).filter((c) => {
    if (seen.has(c)) return false;
    seen.add(c); return true;
  });
}

module.exports = { CITIES, ABBR, extractCities };
