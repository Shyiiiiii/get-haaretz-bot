const INTRACITY_HINT = 'פנימי';

const expand = (t) => PLACES[normalize(t)] || normalize(t);
const isPlace = (t) => !NOISE.has(t);
const isHood = (phrase) => HOODS.has(normalize(phrase));

// נרמול איות נפוץ: קריית→קרית, רווחים
function normalize(s) {
  return String(s).replace(/קריית/g, 'קרית').replace(/\s+/g, ' ').trim();
}

/** מזהה עיר ושכונה מתוך שם מקום. שכונת ירושלים -> {city:'ירושלים', hood}. */
function resolveCity(phrase) {
  const p = normalize(phrase);
  if (HOODS.has(p)) return { city: 'ירושלים', hood: p };
  return { city: p, hood: null };
}

